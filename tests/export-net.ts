// usage: tsx tests/export-net.ts <net.json>  -> writes lib/net-weights.ts (int16-quantised, base64)
import * as fs from "node:fs";
const j = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const all: number[] = [...j.w1, ...j.b1, ...j.w2, j.b2];
const max = all.reduce((m, x) => Math.max(m, Math.abs(x)), 0);
const q = Int16Array.from(all, (x) => Math.round((x / max) * 32767));
const b64 = Buffer.from(q.buffer).toString("base64");
fs.writeFileSync("lib/net-weights.ts", `// Generated by tests/export-net.ts — value network trained by self-play (${j.games} games).\nexport const NET_H = ${j.h};\nexport const NET_SCALE = ${max / 32767};\nexport const NET_B64 =\n  "${b64}";\n`);
console.log("hidden", j.h, "games", j.games, "bytes", b64.length);
